export function getGalleryMediaBySlug(slug: string) {
  return galleryMedia.find((gallery) => gallery.slug === slug);
}

export function hasGalleryMedia(
  gallery: GalleryMedia | undefined,
): gallery is GalleryMedia {
  return Boolean(gallery && (gallery.photos.length || gallery.videos.length));
}

export function getVideoEmbedUrl(url: string) {
  const embedUrl = url.replace(
    "https://player.mediadelivery.net/play/",
    "https://iframe.mediadelivery.net/embed/",
  );

  return `${embedUrl}?autoplay=false&loop=false&muted=true&preload=true&responsive=true&playsinline=true`;
}
